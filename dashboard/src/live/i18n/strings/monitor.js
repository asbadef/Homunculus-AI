// src/live/i18n/strings/monitor.js — Aşama A's unvalidated monitor strip.
//
// Every clinician who can open the board sees these words (user decision 2, 14.10). They must say
// four things unmistakably, in every language: the values are UNVALIDATED; they are RESEARCH
// decoding; they are not a measurement to decide by; nothing — no alarm, score, notification or
// sound — comes from them. The bedside monitor stays the primary alarm. AZ/RU/EN await a
// native-speaking clinician's review, and for this namespace that review is a deploy gate (plan,
// "Kullanıcıdan gerekenler" 4).
//
// The words are the UI's own in each language: the alarm is az "siqnal", tr "alarm", ru "тревога",
// en "alarm" (nav.alarms); the bell is named by its own label (shell.bell: "Cavab gözləyən
// siqnallar", "Yanıt bekleyen alarmlar", "Тревоги без ответа", "Alarms awaiting response"); the
// Settings tab the legend lives in by the tab's own name (signals.tab). ru says "не валидировано"
// rather than "не проверено": two parameters WERE checked against the screen (`ev.*`), and the
// strip is "partly checked" in places, so "not checked" would contradict itself. `p.*` are the
// monitor's own labels, so the strip can be read against the bedside screen; they are
// language-neutral (strings.test.js NEUTRAL, AZ_SAME_AS_TR). `ev.*` restate the design's §4.1 and
// docs/INFINITY-PARAMETER-RECORDS.md:36-50 — no sample count is recorded for any, and `legendN`
// says so. NBP is shown with the time its value last CHANGED, an upper bound of the measurement
// (`nbpMeasured`: "≤", never "at"); before a change has been seen it says it awaits one
// (`nbpWaiting`); `legendNbp` says what the time means (an upper bound), the 2-hour limit, the
// waits after a hub restart or an interruption of the monitor's data, and that a changed
// patient's bed may show the previous patient's NBP.
