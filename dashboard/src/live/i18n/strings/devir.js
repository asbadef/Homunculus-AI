// sealed system summary. What every language must keep:
//   - a handover is two signatures: the outgoing person signs, the receiver she chose countersigns (owner D2);
//   - an unanswered critical alarm on the patient's card holds the outgoing signature (D3) — said as THIS screen's
//     lock, never as the discharge's (`kabul.err.criticalAlarmOpen` is about a discharge);
//   - the note's hint asks for no names or identity numbers and no working diagnosis: it is kept with the handover;
//   - the summary is what the board showed AT THE SIGNATURE, never the present — its title says so;
