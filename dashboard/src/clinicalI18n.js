const STORAGE_KEY = "homunculus-clang";

// Auto-detect the UI language from the browser/OS locale (navigator.language) so an
// Azerbaijani device is greeted in AZ on first launch — a strong "made for us" signal in
// the AZ market. Only used when the user has no explicit stored preference yet.
//
// Auto-detection is deliberately limited to the two languages the wards actually speak.
// The ward PCs at the pilot site run an English-locale Chrome, so detecting the full
// LANG_KEYS set landed every clinician on an English UI over Turkish patient data — the
// opposite of the "made for us" signal this function exists to give. EN and RU remain
// selectable; a stored preference still wins over everything here.
const AUTO_DETECT_LANGS = ["tr", "az"];

export function detectClang() {
  try {
    const cands = [navigator.language, ...(navigator.languages || [])].filter(Boolean);
    for (const c of cands) {
      const two = String(c).slice(0, 2).toLowerCase();
      if (AUTO_DETECT_LANGS.includes(two)) return two;
    }
  } catch {
    /* ignore */
  }
  return "tr";
}

export function storedClang() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (LANG_KEYS.includes(v)) return v;
    return detectClang();
  } catch {
    return "tr";
  }
}
export function persistClang(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
}
