// Every clinician who can open the board sees these words (user decision 2, 14.10). They must say
// four things unmistakably, in every language: the values are UNVALIDATED; they are RESEARCH
// decoding; they are not a measurement to decide by; nothing — no alert, score, notification or
// sound — comes from them. The bedside monitor stays the primary alarm. AZ/RU/EN await a
// native-speaking clinician's review, and for this namespace that review is a deploy gate (plan,
// "Kullanıcıdan gerekenler" 4).
//
// The alarm word is the UI's own in each language (az "siqnal", as nav.alarms and the bell say;
// tr "alarm"; ru "тревога"), and the Settings tab the legend lives in is named as the tab itself
// is (signals.tab). `p.*` are the monitor's own labels, so the strip can be read against the bedside
// screen; they are language-neutral (strings.test.js NEUTRAL, AZ_SAME_AS_TR). `ev.*` restate the
// design's §4.1 and docs/INFINITY-PARAMETER-RECORDS.md:36-50 — no sample count is recorded for any,
// and `legendN` says so.
